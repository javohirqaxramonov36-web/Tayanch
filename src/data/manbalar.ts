export function rasmiyManbalar(idlar: string[] = []): Manba[] {
  return idlar
    .map((id) => manbalar.find((m) => m.id === id))
    .filter((m): m is Manba => !!m && m.tekshiruvDarajasi === 'rasmiy');
}
